/**
 * REQ-005 L-5 (lockfile integrity side channel and comparison, `[registry]`
 * third template) and N-1 (normalizer input cap, linear trailing-paren strip).
 * AC-L5-1, AC-L5-2 (line), AC-L5-3, AC-N1-1, AC-N1-2; ADR-007 Karar 12, 13.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { MAX_LICENSE_INPUT_CODE_POINTS, normalizeLicense, stripTrailingParenthetical } from '../../src/analysis/licenseNormalizer';
import { registrySummaryLine } from '../../src/enrichment/effectiveLicense';
import { IntegrityCollector, MAX_LOCK_INTEGRITY_CHARS, compareLockIntegrity, isAcceptableLockIntegrity } from '../../src/enrichment/lockIntegrity';
import type { ArchiveCandidate } from '../../src/enrichment/types';
import { parseManifests } from '../../src/scanner/parsers';

const sha512 = (s: string) => crypto.createHash('sha512').update(s).digest('base64');
const A = sha512('archive-a');
const B = sha512('archive-b');
const candidate = (digests: string[], algorithm: ArchiveCandidate['algorithm'] = 'sha512'): ArchiveCandidate => ({ url: 'https://registry.npmjs.org/x/-/x-1.0.0.tgz', algorithm, digests, size: null, filename: null });

let dir = '';
beforeEach(() => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ossr-l5-'));
});
afterEach(() => {
  fs.rmSync(dir, { recursive: true, force: true });
});

function write(name: string, content: unknown): void {
  fs.writeFileSync(path.join(dir, name), typeof content === 'string' ? content : JSON.stringify(content, null, 2));
}

const PKG = { name: 'app', version: '1.0.0', dependencies: { 'left-pad': '^1.3.0', '@scope/pkg': '^2.0.0' } };

const LOCKS: Record<string, unknown> = {
  v1: {
    name: 'app',
    lockfileVersion: 1,
    dependencies: {
      'left-pad': { version: '1.3.0', integrity: `sha512-${A}` },
      '@scope/pkg': { version: '2.0.0', integrity: `sha1-abc sha512-${B}` },
    },
  },
  v2: {
    name: 'app',
    lockfileVersion: 2,
    packages: {
      '': { name: 'app', version: '1.0.0', dependencies: PKG.dependencies },
      'node_modules/left-pad': { version: '1.3.0', integrity: `sha512-${A}` },
      'node_modules/@scope/pkg': { version: '2.0.0', integrity: `sha1-abc sha512-${B}` },
    },
    dependencies: {
      'left-pad': { version: '1.3.0', integrity: `sha512-${A}` },
      '@scope/pkg': { version: '2.0.0', integrity: `sha1-abc sha512-${B}` },
    },
  },
  v3: {
    name: 'app',
    lockfileVersion: 3,
    packages: {
      '': { name: 'app', version: '1.0.0', dependencies: PKG.dependencies },
      'node_modules/left-pad': { version: '1.3.0', integrity: `sha512-${A}` },
      'node_modules/@scope/pkg': { version: '2.0.0', integrity: `sha1-abc sha512-${B}` },
    },
  },
};

const YARN = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


left-pad@^1.3.0:
  version "1.3.0"
  resolved "https://registry.yarnpkg.com/left-pad/-/left-pad-1.3.0.tgz#5b8a3a7765dfe001261dde915589e782f8c94d1e"
  integrity sha512-${A}

"@scope/pkg@^2.0.0":
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/@scope/pkg/-/pkg-2.0.0.tgz"
  integrity "sha1-abc sha512-${B}"
`;

describe('AC-L5-1 / AC-L5-3: parser side channel', () => {
  it.each(['v1', 'v2', 'v3'])('AC-L5-1 / AC-L5-3: package-lock %s integrity reaches the collector; the parse result is identical with and without it', (version) => {
    write('package.json', PKG);
    write('package-lock.json', LOCKS[version]);
    const plain = parseManifests(dir, ['nodejs'], 'scan-1');
    const collector = new IntegrityCollector();
    const withChannel = parseManifests(dir, ['nodejs'], 'scan-1', { integrityCollector: collector });
    expect(withChannel).toEqual(plain);
    expect(JSON.stringify(withChannel)).not.toContain('sha512-');
    for (const dep of withChannel.dependencies) expect(dep).not.toHaveProperty('integrity');
    const byName = Object.fromEntries(collector.records.map((r) => [r.name, r]));
    expect(byName['left-pad']).toMatchObject({ version: '1.3.0', integrity: `sha512-${A}` });
    expect(byName['@scope/pkg']).toMatchObject({ version: '2.0.0' });
    expect(byName['@scope/pkg'].integrity).toContain(`sha512-${B}`);
  });

  it('AC-L5-1 / AC-L5-3: yarn.lock v1 integrity reaches the collector; the parse result is unchanged', () => {
    write('package.json', PKG);
    write('yarn.lock', YARN);
    const plain = parseManifests(dir, ['nodejs'], 'scan-1');
    const collector = new IntegrityCollector();
    const withChannel = parseManifests(dir, ['nodejs'], 'scan-1', { integrityCollector: collector });
    expect(withChannel).toEqual(plain);
    const leftPad = collector.records.find((r) => r.name === 'left-pad');
    expect(leftPad).toMatchObject({ version: '1.3.0', integrity: `sha512-${A}` });
    const scoped = collector.records.find((r) => r.name === '@scope/pkg');
    expect(scoped?.integrity).toContain(`sha512-${B}`);
  });

  it('AC-L5-1: side-channel bounds: length <= 1024 and SRI character set, deduplicated', () => {
    expect(MAX_LOCK_INTEGRITY_CHARS).toBe(1024);
    expect(isAcceptableLockIntegrity(`sha512-${A}`)).toBe(true);
    expect(isAcceptableLockIntegrity('x'.repeat(1025))).toBe(false);
    expect(isAcceptableLockIntegrity('sha512-<script>')).toBe(false);
    expect(isAcceptableLockIntegrity('sha512-a\nb')).toBe(false);
    expect(isAcceptableLockIntegrity('')).toBe(false);
    expect(isAcceptableLockIntegrity(42)).toBe(false);
    const c = new IntegrityCollector();
    c.add('.', 'a', '1.0.0', `sha512-${A}`);
    c.add('.', 'a', '1.0.0', `sha512-${A}`);
    c.add('.', 'b', '1.0.0', 'bad\u0000value');
    expect(c.records).toEqual([{ manifestPath: '.', name: 'a', version: '1.0.0', integrity: `sha512-${A}` }]);
  });
});

describe('AC-L5-1: comparison', () => {
  it('AC-L5-1: match / mismatch / not_comparable', () => {
    expect(compareLockIntegrity([{ integrity: `sha512-${A}` }], [candidate([A])])).toBe('match');
    expect(compareLockIntegrity([{ integrity: `sha512-${B}` }], [candidate([A])])).toBe('mismatch');
    // Several SRI items: one sha512 match is enough.
    expect(compareLockIntegrity([{ integrity: `sha1-abc sha512-${B} sha512-${A}` }], [candidate([A])])).toBe('match');
    // No sha512 on one side, broken value, no candidate.
    expect(compareLockIntegrity([{ integrity: 'sha1-q83vEjRWeJA=' }], [candidate([A])])).toBe('not_comparable');
    expect(compareLockIntegrity([{ integrity: 'sha512-notbase64!!' }], [candidate([A])])).toBe('not_comparable');
    expect(compareLockIntegrity([], [candidate([A])])).toBe('not_comparable');
    expect(compareLockIntegrity([{ integrity: `sha512-${A}` }], null)).toBe('not_comparable');
    expect(compareLockIntegrity([{ integrity: `sha512-${A}` }], [candidate(['0123abcd'], 'sha1')])).toBe('not_comparable');
    // Conservative: two manifests point the same key at different archives.
    expect(compareLockIntegrity([{ integrity: `sha512-${A}` }, { integrity: `sha512-${B}` }], [candidate([A])])).toBe('mismatch');
  });
});

describe('AC-L5-2: [registry] line (REQ-004 contract 1.2.0 §8)', () => {
  const ok = { status: 'found', usedHint: false };
  it('AC-L5-2: X = 0 -> byte for byte the 1.1.0 line (or none)', () => {
    expect(registrySummaryLine([ok, ok] as never, true)).toBeNull();
    expect(registrySummaryLine([ok, { status: 'unreachable', usedHint: true }, { status: 'error', usedHint: false }] as never, true)).toBe(
      '[registry] Registry lookup incomplete for 2 package(s) (unreachable: 1, error: 1, time budget exceeded: 0); license from lockfile (unverified): 1, no license: 1.',
    );
  });

  it('AC-L5-2: mismatches alone -> the third template with X; with incomplete keys -> suffix', () => {
    expect(registrySummaryLine([ok, { ...ok, integrityMismatch: true }, { ...ok, integrityMismatch: true }] as never, true)).toBe(
      '[registry] Lockfile integrity mismatch for 2 package(s); registry license and lockfile hint not used.',
    );
    expect(registrySummaryLine([{ ...ok, integrityMismatch: true }, { status: 'budget_exceeded', usedHint: false }] as never, true)).toBe(
      '[registry] Registry lookup incomplete for 1 package(s) (unreachable: 0, error: 0, time budget exceeded: 1); license from lockfile (unverified): 0, no license: 1. Lockfile integrity mismatch: 1 package(s) (registry license and lockfile hint not used).',
    );
  });
});

describe('N-1: normalizer hardening', () => {
  it('AC-N1-1: input is cut at 1000 code points before normalization (ADR-007 Karar 13 truncateCodePoints: 999 + "…"; surrogate pairs counted once)', () => {
    expect(MAX_LICENSE_INPUT_CODE_POINTS).toBe(1000);
    const long = `Custom ${'X'.repeat(1500)}`;
    const cut = `${[...long].slice(0, 999).join('')}…`;
    expect(normalizeLicense(long).normalized).toBe(normalizeLicense(cut).normalized);
    expect([...normalizeLicense(long).normalized].length).toBe(1000);
    const exact = `MIT${' '.repeat(997)}`;
    expect(normalizeLicense(exact).spdxId).toBe('MIT');
    const emoji = '\u{1F600}'.repeat(1200);
    const r = normalizeLicense(emoji);
    expect([...r.normalized].length).toBeLessThanOrEqual(1000);
    expect(r.normalized).not.toMatch(/[\uD800-\uDBFF]$/);
    expect(r.originalRaw).toBe(emoji);
  });

  it('AC-N1-1: inputs <= 1000 code points keep their former results', () => {
    expect(normalizeLicense('MIT License (MIT)').spdxId).toBe('MIT');
    expect(normalizeLicense('Apache 2.0').spdxId).toBe('Apache-2.0');
    expect(normalizeLicense('MIT OR Apache-2.0').isSpdxExpression).toBe(true);
    expect(normalizeLicense('GPL-3.0-or-later').spdxId).toBe('GPL-3.0-or-later');
  });

  it("AC-N1-2: linear paren strip equals the old /\\s*\\([^)]*\\)\\s*$/ semantics (exhaustive short inputs, 'A (B (C)' -> 'A')", () => {
    const old = (s: string) => s.replace(/\s*\([^)]*\)\s*$/, '');
    expect(stripTrailingParenthetical('A (B (C)')).toBe('A');
    expect(stripTrailingParenthetical('MIT License (MIT)  ')).toBe('MIT License');
    expect(stripTrailingParenthetical('(x)')).toBe('');
    expect(stripTrailingParenthetical('a) (b)')).toBe('a)');
    expect(stripTrailingParenthetical('no parens')).toBe('no parens');
    const alphabet = ['a', ' ', '(', ')', '\t'];
    let checked = 0;
    const visit = (prefix: string, depth: number) => {
      expect(stripTrailingParenthetical(prefix), JSON.stringify(prefix)).toBe(old(prefix));
      checked++;
      if (depth === 0) return;
      for (const ch of alphabet) visit(prefix + ch, depth - 1);
    };
    visit('', 7);
    expect(checked).toBeGreaterThan(90_000);
  });

  it('AC-N1-2: adversarial 100 000-character inputs finish within 2 s (strip and normalize)', () => {
    const inputs = ['('.repeat(100_000), `MIT (${'a'.repeat(100_000)}`, `${'(a'.repeat(50_000)})`, `${' ('.repeat(50_000)})`, `a${' '.repeat(100_000)})`, `${'MIT OR '.repeat(15_000)}MIT`];
    for (const input of inputs) {
      const started = performance.now();
      stripTrailingParenthetical(input);
      normalizeLicense(input);
      expect(performance.now() - started, input.slice(0, 12)).toBeLessThan(2_000);
    }
  });
});
